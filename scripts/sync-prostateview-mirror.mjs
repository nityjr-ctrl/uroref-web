import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceArg = process.argv[2] ?? process.env.PROSTATEVIEW_DIST;

if (!sourceArg) {
  console.error("Usage: npm run sync:prostateview -- <path-to-prostateview-dist>");
  process.exit(1);
}

const source = path.resolve(sourceArg);
const targetRoot = path.resolve(repoRoot, "public");
const target = path.resolve(targetRoot, "prostateview");

if (!existsSync(path.join(source, "index.html"))) {
  console.error(`Source does not look like an Astro dist directory: ${source}`);
  process.exit(1);
}

if (!target.startsWith(targetRoot + path.sep)) {
  console.error(`Refusing to write outside public/: ${target}`);
  process.exit(1);
}

await rm(target, { recursive: true, force: true });
await mkdir(targetRoot, { recursive: true });
await cp(source, target, { recursive: true });
await rm(path.join(target, "CNAME"), { force: true });
await rm(path.join(target, ".nojekyll"), { force: true });

const textExtensions = new Set([
  ".html",
  ".css",
  ".js",
  ".json",
  ".webmanifest",
  ".txt",
  ".svg",
]);

const rootPathStarts = [
  "_astro",
  "about",
  "case",
  "cases",
  "compare",
  "demo-cases",
  "draco",
  "figures",
  "fonts",
  "icons",
  "images",
  "method",
  "models_ar_human",
  "models_ar",
  "models",
  "upload",
  "v2",
  "viewer",
  "manifest-v2.webmanifest",
  "manifest.webmanifest",
  "logo-symbol.png",
  "logo.png",
  "prostateview_hero_loop.mp4",
  "prostateview_intro_poster.jpg",
  "prostateview_intro.mp4",
  "social-preview.png",
  "sw.js",
].map((value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));

const rootPathPattern = new RegExp(
  `(["'\`(=:\\s])\\/(?!\\/|prostateview\\/)(${rootPathStarts.join("|")})(?=[\\/#?\"'\`)\\s]|$)`,
  "g",
);

function prefixRootPaths(text) {
  return text
    .replace(rootPathPattern, "$1/prostateview/$2")
    .replace(/return(["'])\/\1\+/g, "return$1/prostateview/$1+");
}

function addNoIndex(html) {
  if (html.includes('name="robots"')) return html;
  return html.replace(/<head([^>]*)>/i, '<head$1>\n    <meta name="robots" content="noindex">');
}

async function rewriteDirectory(dir) {
  const entries = await import("node:fs/promises").then((fs) => fs.readdir(dir, { withFileTypes: true }));
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await rewriteDirectory(full);
      continue;
    }
    if (!textExtensions.has(path.extname(entry.name))) continue;
    let text = await readFile(full, "utf8");
    text = prefixRootPaths(text);
    if (entry.name.endsWith(".html")) text = addNoIndex(text);
    await writeFile(full, text);
  }
}

await rewriteDirectory(target);

await writeFile(
  path.join(target, "README.md"),
  [
    "# ProstateView mirror output",
    "",
    "Generated by `npm run sync:prostateview -- <path-to-prostateview-dist>` from the UroRef repository.",
    "",
    "This temporary mirror is intended for `https://uroref.com/prostateview/`.",
    "Do not edit these files by hand in the UroRef repository.",
    "",
    "Teardown: remove the ProstateView mirror workflow and delete `public/prostateview/` from the UroRef site repository.",
    "",
  ].join("\n"),
);

console.log(`Synced ProstateView mirror from ${source} to ${target}`);
